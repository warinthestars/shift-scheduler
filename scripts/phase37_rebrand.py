def decide(pref, util, shade, alpha, line, seg, path):
    """'B' = brand gold, 'K' = keep green."""
    for p, piece in KEEP:
        if p == path and piece in line:
            return "K"
    for p, piece in GOLD:
        if p == path and piece in line:
            return "B"
    shade = int(shade)
    interactive = any(x in pref for x in INTERACTIVE)
    status = bool(STATUS.search(line))
    if util in ("accent", "from", "to", "via", "shadow"):
        return "B"
    if util == "ring":
        return "B" if (interactive or not alpha) and not status else "K"
    if util == "bg":
        if alpha or shade >= 900:                      # a tinted or very dark surface is a status surface
            return "K"
        return "K" if status and not interactive else "B"      # a solid fill is a button, a tab or a dot
    if util == "border":
        if interactive:
            return "B"
        if alpha or shade >= 700:
            return "K"
        return "K" if status else "B"
    # text
    if interactive:
        return "B"
    tinted = bool(re.search(r"(?:bg|border)-emerald-\d{2,3}/\d", seg)) or bool(re.search(r"bg-emerald-9\d0", seg))
    return "K" if (tinted or status) else "B"


def gold_class(pref, util, shade, alpha):
    shade = int(shade)
    if util == "bg" and not alpha and shade in (400, 500, 600):
        if "hover:" in pref:
            shade = {400: 400, 500: 400, 600: 500}[shade]        # a hover is one step lighter than the button
        else:
            shade = min(shade, 500)                               # every solid button is the logo's gold
    return f"{pref}{util}-brand-{shade}{alpha}"


def recolor_line(line, path):
    for old, new in PHRASES:
        line = line.replace(old, new)
    if "emerald" not in line:
        return line
    out = []
    for seg in QUOTES.split(line):                    # one quoted class list at a time
        flip = {"base": False, "hover": False}

        def swap(m, seg=seg, flip=flip):
            pref, util, shade, alpha = m.group(1), m.group(2), m.group(3), m.group(4) or ""
            if decide(pref, util, shade, alpha, line, seg, path) != "B":
                return m.group(0)
            if util == "bg" and not alpha and int(shade) in (400, 500, 600):
                flip["hover" if "hover:" in pref else "base"] = True
            return gold_class(pref, util, shade, alpha)

        new = TOKEN.sub(swap, seg)
        if flip["base"]:                              # white text can't be read on gold
            new = re.sub(r"(?<![\w:-])text-white(?![\w/-])", "text-slate-950", new)
        if flip["hover"]:
            new = re.sub(r"(?<![\w-])hover:text-white(?![\w/-])", "hover:text-slate-950", new)
        out.append(new)
    return "".join(out)


