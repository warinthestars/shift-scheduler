def rename_line(line):
    if NAME_SKIP.search(line):
        return line
    return NAME.sub("ShiftUp", line)


def transform(text, path):
    """text with LF line endings -> the rebranded text"""
    do_name = path in NAME_FILES or any(path.startswith(d + "/") for d in NAME_DIRS)
    do_color = any(path.startswith(d + "/") for d in COLOR_DIRS)
    lines = []
    for line in text.split("\n"):
        if do_color:
            line = recolor_line(line, path)
        if do_name:
            line = rename_line(line)
        lines.append(line)
    text = "\n".join(lines)
    for p, old, new in SWAPS:
        if p == path:
            if text.count(old) != 1:
                raise SystemExit(f"STOP: {path}: expected exactly one {old!r}, found {text.count(old)}")
            text = text.replace(old, new)
    return text


