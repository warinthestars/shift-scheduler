def candidates(root):
    """Every file the rules look at."""
    out = set(f for f in NAME_FILES + [p for p, _o, _n in SWAPS] if os.path.isfile(os.path.join(root, f)))
    for d in set(NAME_DIRS + COLOR_DIRS):
        for base, dirs, files in os.walk(os.path.join(root, d)):
            dirs[:] = [x for x in dirs if x not in ("__pycache__", "node_modules", "dist", ".vite")]
            for f in files:
                if f.endswith((".py", ".jsx", ".js", ".css")):
                    out.add(os.path.relpath(os.path.join(base, f), root).replace(os.sep, "/"))
    return sorted(out)


def fingerprint(text):
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def load(root, path, strict=True):
    """-> (text with LF line endings, True when the file uses Windows line endings)"""
    with open(os.path.join(root, path), "rb") as fh:
        raw = fh.read().decode("utf-8")
    crlf = raw.count("\r\n")
    if strict and crlf and crlf != raw.count("\n"):
        raise SystemExit("STOP: %s mixes Windows and Unix line endings. Nothing was changed." % path)
    return raw.replace("\r\n", "\n"), bool(crlf)


def main():
    args = sys.argv[1:]
    if [a for a in args if a != "--check"]:
        raise SystemExit("STOP: the only option is --check. Nothing was changed.")
    check_only = "--check" in args
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    for need in ("frontend/src", "backend/src", "docker-compose.yaml"):
        if not os.path.exists(os.path.join(root, need)):
            raise SystemExit("STOP: %s not found under %s. This file belongs in <repo>/scripts/." % (need, root))

    todo, done, odd, missing = [], [], [], []
    for path in sorted(EXPECT):
        before, after = EXPECT[path]
        if not os.path.isfile(os.path.join(root, path)):
            missing.append(path)
            continue
        text, crlf = load(root, path)
        mark = fingerprint(text)
        if mark == after:
            done.append(path)
        elif mark == before:
            todo.append((path, text, crlf, after))
        else:
            odd.append(path)

    if not todo:
        print("Already applied: none of the %d files is in its 0.36.1 state. Nothing was changed." % len(EXPECT))
        return 0
    if missing or odd:
        for p in missing:
            print("  missing:    " + p)
        for p in odd:
            print("  unexpected: " + p + "   (not the 0.36.1 file, and not the finished file)")
        raise SystemExit("STOP: %d file(s) are not what this script was written against. Nothing was changed. "
                         "Report this list; do not edit the files or the script to get past it." % (len(missing) + len(odd)))

    results = []
    for path, text, crlf, after in todo:
        new = transform(text, path)
        if fingerprint(new) != after:
            raise SystemExit("STOP: %s: the result is not the expected one. Nothing was changed. "
                             "(Was this script edited?)" % path)
        results.append((path, new, crlf))

    extra = []
    for path in candidates(root):
        if path in EXPECT:
            continue
        text, _crlf = load(root, path, strict=False)
        if transform(text, path) != text:
            extra.append(path)
    if extra:
        for p in extra:
            print("  not in the list: " + p)
        raise SystemExit("STOP: %d file(s) outside the expected list use the old name or the old colours. Nothing was "
                         "changed. Report this list." % len(extra))

    if check_only:
        print("Check passed: %d file(s) would change, %d already done. Nothing was changed (--check)." % (len(results), len(done)))
        return 0
    for path, new, crlf in results:
        # written beside the file first and then swapped in, so a file is never left half written
        data = (new.replace("\n", "\r\n") if crlf else new).encode("utf-8")
        full = os.path.join(root, path)
        tmp = full + ".phase37.tmp"
        with open(tmp, "wb") as fh:
            fh.write(data)
        shutil.copymode(full, tmp)
        os.replace(tmp, full)
    print("Done: %d file(s) changed, %d were already done." % (len(results), len(done)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
